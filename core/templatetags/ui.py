@register.simple_tag
def icon(name, css_class="h-5 w-5", filled=False, stroke="1.6"):
    paths = ICONS.get(name)
    if paths is None:
        return ""
    fill = "currentColor" if filled else "none"
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{}" stroke="currentColor" '
        'stroke-width="{}" stroke-linecap="round" stroke-linejoin="round" class="{}" aria-hidden="true" '
        'focusable="false">{}</svg>',
        fill,
        stroke,
        css_class,
        mark_safe(paths),  # static, trusted markup defined above
    )


@register.filter
def tmdb_image(path, size="w342"):
    """Build a TMDB CDN URL for a poster/backdrop/profile path; '' when missing."""
    if not path:
        return ""
    return f"{settings.TMDB['IMAGE_BASE_URL']}/{size}{path}"


@register.filter
def runtime(minutes):
    try:
        minutes = int(minutes)
    except (TypeError, ValueError):
        return ""
    if minutes <= 0:
        return ""
    hours, mins = divmod(minutes, 60)
    return f"{hours}h {mins:02d}m" if hours else f"{mins}m"


@register.filter
def score(value):
    """Format a 0-10 score with one decimal; '' when absent."""
    try:
        value = float(value)
    except (TypeError, ValueError):
        return ""
    return f"{value:.1f}" if value > 0 else ""


@register.filter
def upto(value):
    """`10|upto` -> 1..10, for rendering rating scales."""
    return range(1, int(value) + 1)


@register.filter
def money(value):
    try:
        value = int(value)
    except (TypeError, ValueError):
        return ""
    return f"${value:,}" if value > 0 else ""


@register.filter
def in_set(value, collection):
    """`movie.tmdb_id|in_set:favorite_ids` -> bool."""
    try:
        return value in (collection or ())
    except TypeError:
        return False
